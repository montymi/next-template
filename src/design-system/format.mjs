const colorKeys = [
	'background',
	'surface',
	'surfaceAlt',
	'text',
	'muted',
	'primary',
	'primaryStrong',
	'primaryText',
	'accent',
	'accentSurface',
	'border',
	'ring',
]
const fontValues = [
	'Inter, Arial, sans-serif',
	'system-ui, Arial, sans-serif',
	'Newsreader, Georgia, serif',
	"Georgia, 'Times New Roman', serif",
]
const topKeys = [
	'name',
	'inspiration',
	'fonts',
	'spacing',
	'radii',
	'light',
	'dark',
]
const object = (value) =>
	value !== null && typeof value === 'object' && !Array.isArray(value)
const sameKeys = (value, keys) =>
	object(value) &&
	Object.keys(value).length === keys.length &&
	keys.every((key) => Object.hasOwn(value, key))
export class TokenValidationError extends Error {
	constructor(message) {
		super(message)
		this.name = 'TokenValidationError'
	}
}
/** @param {unknown} value @returns {import('./types').DesignTokens} */
export function validateTokens(value) {
	if (!sameKeys(value, topKeys))
		throw new TokenValidationError(
			'The token document has missing or unexpected fields.',
		)
	for (const key of ['name', 'inspiration'])
		if (
			typeof value[key] !== 'string' ||
			!value[key].trim() ||
			value[key].length > 240 ||
			/[\u0000-\u001f]/.test(value[key])
		)
			throw new TokenValidationError(`Invalid ${key}.`)
	for (const mode of ['light', 'dark']) {
		if (!sameKeys(value[mode], colorKeys))
			throw new TokenValidationError(`Invalid ${mode} color fields.`)
		for (const key of colorKeys)
			if (
				typeof value[mode][key] !== 'string' ||
				!/^#[0-9a-f]{6}$/i.test(value[mode][key])
			)
				throw new TokenValidationError(
					`Use a six-digit hex color for ${mode}.${key}.`,
				)
	}
	if (
		!sameKeys(value.fonts, ['body', 'display']) ||
		!fontValues.includes(value.fonts.body) ||
		!fontValues.includes(value.fonts.display)
	)
		throw new TokenValidationError('Choose a supported local or system font.')
	for (const [name, keys, maximum] of [
		['spacing', ['1', '2', '3', '4', '5', '6', '7', '8', '9'], 192],
		['radii', ['small', 'medium', 'large'], 80],
	]) {
		if (!sameKeys(value[name], keys))
			throw new TokenValidationError(`Invalid ${name} fields.`)
		let previous = -1
		for (const key of keys) {
			const n = value[name][key]
			if (!Number.isFinite(n) || n < 0 || n > maximum || n < previous)
				throw new TokenValidationError(
					`${name} must use increasing sizes between 0 and ${maximum}.`,
				)
			previous = n
		}
	}
	return structuredClone(value)
}
/** @param {import('./types').DesignTokens} input */
export function generateTokenCss(input) {
	const tokens = validateTokens(input)
	const kebab = (name) =>
		name.replace(/[A-Z]/g, (letter) => `-${letter.toLowerCase()}`)
	const colors = (mode) =>
		Object.entries(tokens[mode]).map(
			([name, value]) => `\t--${kebab(name)}: ${value.toLowerCase()};`,
		)
	const sizes = (map, prefix) =>
		Object.entries(map).map(
			([name, value]) => `\t--${prefix}-${kebab(name)}: ${value}px;`,
		)
	return `/* Generated by npm run tokens. Edit src/design-system/tokens.json. */\n:root {\n${[...colors('light'), ...sizes(tokens.spacing, 'space'), ...sizes(tokens.radii, 'radius'), ...Object.entries(tokens.fonts).map(([name, value]) => `\t--font-${name}: ${value};`)].join('\n')}\n}\n.dark {\n${colors('dark').join('\n')}\n}\n`
}
